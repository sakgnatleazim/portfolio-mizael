// Normalize database data to make sure old structure migrates gracefully
export function normalizePortfolioData(data) {
  if (!data) return defaultPortfolioData;

  const normalized = { ...defaultPortfolioData };

  // Normalize Hero
  normalized.hero = { ...defaultPortfolioData.hero, ...data.hero };
  for (const key of ['eyebrow', 'title', 'desc', 'ctaPrimaryText', 'ctaOutlineText']) {
    if (data.hero?.[key]) {
      if (!normalized.hero[`${key}_id`]) normalized.hero[`${key}_id`] = data.hero[key];
      if (!normalized.hero[`${key}_en`]) normalized.hero[`${key}_en`] = data.hero[key];
    }
  }

  // Normalize About
  normalized.about = { ...defaultPortfolioData.about, ...data.about };
  for (const key of ['title', 'text1', 'text2', 'text3']) {
    if (data.about?.[key]) {
      if (!normalized.about[`${key}_id`]) normalized.about[`${key}_id`] = data.about[key];
      if (!normalized.about[`${key}_en`]) normalized.about[`${key}_en`] = data.about[key];
    }
  }

  // Normalize About details
  if (Array.isArray(data.about?.details)) {
    normalized.about.details = data.about.details.map((d, i) => {
      const def = defaultPortfolioData.about.details[i] || {};
      const norm = { ...def, ...d };
      if (d.label) {
        if (!norm.label_id) norm.label_id = d.label;
        if (!norm.label_en) norm.label_en = d.label;
      }
      if (d.value) {
        if (!norm.value_id) norm.value_id = d.value;
        if (!norm.value_en) norm.value_en = d.value;
      }
      return norm;
    });
  }

  // Normalize Skills
  if (Array.isArray(data.skills)) {
    normalized.skills = data.skills.map(s => {
      const norm = { ...s };
      if (s.level) {
        if (!norm.level_id) norm.level_id = s.level;
        if (!norm.level_en) norm.level_en = s.level;
      }
      return norm;
    });
  } else {
    normalized.skills = defaultPortfolioData.skills;
  }

  // Normalize Projects
  if (Array.isArray(data.projects)) {
    normalized.projects = data.projects.map(p => {
      const norm = { ...p };
      for (const key of ['type', 'name', 'desc']) {
        if (p[key]) {
          if (!norm[`${key}_id`]) norm[`${key}_id`] = p[key];
          if (!norm[`${key}_en`]) norm[`${key}_en`] = p[key];
        }
      }
      return norm;
    });
  } else {
    normalized.projects = defaultPortfolioData.projects;
  }

  // Normalize Activities
  if (Array.isArray(data.activities)) {
    normalized.activities = data.activities.map(a => {
      const norm = { ...a };
      for (const key of ['title', 'desc']) {
        if (a[key]) {
          if (!norm[`${key}_id`]) norm[`${key}_id`] = a[key];
          if (!norm[`${key}_en`]) norm[`${key}_en`] = a[key];
        }
      }
      return norm;
    });
  } else {
    normalized.activities = defaultPortfolioData.activities;
  }

  // Normalize Organizations
  if (Array.isArray(data.organizations)) {
    normalized.organizations = data.organizations.map(o => {
      const norm = { ...o };
      for (const key of ['name', 'role', 'desc']) {
        if (o[key]) {
          if (!norm[`${key}_id`]) norm[`${key}_id`] = o[key];
          if (!norm[`${key}_en`]) norm[`${key}_en`] = o[key];
        }
      }
      return norm;
    });
  } else {
    normalized.organizations = defaultPortfolioData.organizations;
  }

  // Normalize Certificates (new section)
  if (Array.isArray(data.certificates)) {
    normalized.certificates = data.certificates.map(c => {
      const norm = { ...c };
      norm.title_id = norm.title_id || norm.title || '';
      norm.title_en = norm.title_en || norm.title || '';
      norm.issuer_id = norm.issuer_id || norm.issuer || '';
      norm.issuer_en = norm.issuer_en || norm.issuer || '';
      norm.date = norm.date || '';
      norm.credentialUrl = norm.credentialUrl || '';
      norm.imgUrl = norm.imgUrl || '';
      return norm;
    });
  } else {
    normalized.certificates = defaultPortfolioData.certificates || [];
  }

  // Normalize Contact
  normalized.contact = { ...defaultPortfolioData.contact, ...data.contact };
  for (const key of ['title', 'sub']) {
    if (data.contact?.[key]) {
      if (!normalized.contact[`${key}_id`]) normalized.contact[`${key}_id`] = data.contact[key];
      if (!normalized.contact[`${key}_en`]) normalized.contact[`${key}_en`] = data.contact[key];
    }
  }

  // Normalize Footer
  normalized.footer = { ...defaultPortfolioData.footer, ...data.footer };
  if (data.footer?.text) {
    if (!normalized.footer.text_id) normalized.footer.text_id = data.footer.text;
    if (!normalized.footer.text_en) normalized.footer.text_en = data.footer.text;
  }

  return normalized;
}
